/**
 * AI へ渡すコード文脈のスキーマ定義。
 *
 * profile.ts と同じく VS Code API に依存しない。ここは選択ラインと AI ラインの
 * 接続点であり、片方が VS Code の型を持ち込むと AI 層をエディタ外でテストできなくなる。
 *
 * 収集ロジック（src/context/collector.ts）は 選択/04 (#9) が実装する。
 * このファイルは AI/01 (#10) の AIRequest が参照するために先行して型だけを置いたもので、
 * #9 の実装計画に沿った最小形である。#9 側でフィールドを追加するのは構わないが、
 * 既存フィールドの意味を変える場合は AIRequest の利用側も併せて確認する。
 */

/**
 * コード文脈の入力経路。
 *
 * 推測せず、どのコマンドから呼ばれたかで確定させる。クリップボード経由の取得は
 * 内容しか運ばず出所の情報を持たないため、後から判定することはできない。
 */
export type ContextSource = "editor" | "terminal" | "clipboard";

/**
 * 収集できた文脈の水準。段階的縮退を型として表現する。
 *
 * 取れる情報が多いほど回答が具体的になり、少なくても回答自体は成立する。
 * AI 層はこの値を見てプロンプトの組み立てと期待する回答の粒度を変える。
 */
export type ContextLevel =
  /** コードのみ。位置情報を持たない。 */
  | 1
  /** エディタ選択。コード + 前後 + languageId + ファイル名。 */
  | 2
  /** エディタ選択 + 言語サーバーあり。Lv2 に加えて別ファイルの定義を含む。 */
  | 3;

/**
 * AI へ渡すコード文脈。
 *
 * 生の文字列ではなくこの構造体に揃えることで、AI 層が
 * 「何が取れていて何が取れていないか」を型の上で判断できるようにする。
 */
export interface CodeContext {
  /** 質問対象のコードそのもの。 */
  code: string;
  source: ContextSource;
  contextLevel: ContextLevel;
  /**
   * 選択範囲の前後のコード。
   *
   * 任意項目にしない。選択範囲だけでは判断できないコード（使われている変数の宣言が
   * 選択範囲の外にあるなど）が普通にあり、省略可能にすると呼び出し側が
   * 「今回は要らない」と判断して回答品質が静かに落ちる。
   * 前後を取得できない Lv1 では空文字列になる。
   */
  surroundingCode: string;
  /** VS Code の言語識別子。例: `go`。Lv1 では取得できない。 */
  languageId?: string;
  /** ファイル名。未保存ファイルでも破綻しない値を入れる。Lv1 では取得できない。 */
  fileName?: string;
  /** 選択範囲の開始行（0 始まり）。Lv1 では取得できない。 */
  startLine?: number;
  /** 選択範囲の終了行（0 始まり）。Lv1 では取得できない。 */
  endLine?: number;
}
